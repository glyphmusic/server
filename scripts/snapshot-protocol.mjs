// Keep release builds independent of another repository/tag. Run after shared
// protocol edits (and after committing them in the apps repository); CI
// verifies the committed snapshot builds on its own and matches that commit.
import {readFileSync,writeFileSync,mkdirSync,copyFileSync,readdirSync,existsSync} from 'node:fs';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=new URL('../',import.meta.url);
// GLYPH_APPS_DIR, else a checkout next to this one (`glyph-apps` or `apps`).
const desktop=process.env.GLYPH_APPS_DIR?pathToFileURL(process.env.GLYPH_APPS_DIR.replace(/\/?$/,'/'))
  :['../glyph-apps/','../apps/'].map(p=>new URL(p,root)).find(u=>existsSync(new URL('crates/glyph-protocol/',u)));
if(!desktop) throw new Error('No apps checkout found: set GLYPH_APPS_DIR');
const manifest=readFileSync(new URL('Cargo.toml',desktop),'utf8');
const version=manifest.match(/\[workspace\.package\][\s\S]*?version\s*=\s*"([^"]+)"/)?.[1];
if(!version) throw new Error('Cannot determine protocol version');
const git=args=>execFileSync('git',['-C',fileURLToPath(desktop),...args],{encoding:'utf8'}).trim();
if(git(['status','--porcelain','--','crates/glyph-protocol'])) throw new Error('Commit the protocol change in the apps repository first: the snapshot records its commit');
const output=new URL('release-protocol/',root);
mkdirSync(new URL('src/',output),{recursive:true});
writeFileSync(new URL('Cargo.toml',output),`# Generated by scripts/snapshot-protocol.mjs\n[workspace]\n[package]\nname = "glyph-protocol"\nversion = "${version}"\nedition = "2021"\nlicense = "MIT OR Apache-2.0"\n[features]\nrelease-verify = ["dep:minisign-verify"]\n[dependencies]\nserde = { version = "1", features = ["derive"] }\nserde_json = "1"\nminisign-verify = { version = "0.2", optional = true }\n`);
for(const file of readdirSync(new URL('crates/glyph-protocol/src/',desktop)).filter(f=>f.endsWith('.rs'))) copyFileSync(new URL(`crates/glyph-protocol/src/${file}`,desktop),new URL(`src/${file}`,output));
// The apps commit these files came from; scripts/check-protocol.mjs compares against it.
writeFileSync(new URL('SOURCE',output),`${git(['rev-parse','HEAD'])}\n`);
console.log(`Release protocol snapshot ${version}: ${fileURLToPath(output)}`);
