// Keep release builds independent of another repository/tag. Run after shared
// protocol edits; CI verifies the committed snapshot builds on its own.
import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const desktop=new URL('../glyph/',root);
const manifest=readFileSync(new URL('Cargo.toml',desktop),'utf8');
const version=manifest.match(/\[workspace\.package\][\s\S]*?version\s*=\s*"([^"]+)"/)?.[1];
if(!version) throw new Error('Cannot determine protocol version');
const output=new URL('release-protocol/',root);
mkdirSync(new URL('src/',output),{recursive:true});
writeFileSync(new URL('Cargo.toml',output),`# Generated by scripts/snapshot-protocol.mjs\n[workspace]\n[package]\nname = "glyph-protocol"\nversion = "${version}"\nedition = "2021"\nlicense = "MIT OR Apache-2.0"\n[dependencies]\nserde = { version = "1", features = ["derive"] }\nserde_json = "1"\n`);
for(const file of ['lib.rs','network.rs']) copyFileSync(new URL(`crates/glyph-protocol/src/${file}`,desktop),new URL(`src/${file}`,output));
console.log(`Release protocol snapshot ${version}: ${fileURLToPath(output)}`);
